import { mkdir, cp, writeFile, readFile } from "node:fs/promises";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { parseEnv } from "node:util";

const root = new URL("./", import.meta.url);

// Direct-to-Supabase defaults: CONTINUUM_EXTENSION_SUPABASE_URL/KEY, else the
// web app's public VITE_SUPABASE_URL / VITE_SUPABASE_ANON_KEY from the repo .env.
const repoEnv = await readFile(new URL("../../.env", root), "utf8").then(parseEnv, () => ({}));
const supabaseUrl = process.env.CONTINUUM_EXTENSION_SUPABASE_URL || repoEnv.VITE_SUPABASE_URL || "";
const supabaseKey = process.env.CONTINUUM_EXTENSION_SUPABASE_KEY || repoEnv.VITE_SUPABASE_ANON_KEY || "";
if (supabaseUrl) {
  const url = new URL(supabaseUrl);
  if (url.protocol !== "https:" || !/\.supabase\.(co|in)$/.test(url.hostname)) throw new Error("Extension Supabase URL must be https://<project>.supabase.co");
}
if (/^sb_secret_/i.test(supabaseKey)) throw new Error("Refusing to build: the extension key is a secret key. Use the publishable/anon key.");
if (supabaseKey.startsWith("eyJ")) {
  const role = JSON.parse(Buffer.from(supabaseKey.split(".")[1], "base64url").toString()).role;
  if (role !== "anon") throw new Error(`Refusing to build: the extension key has role "${role}". Use the anon/publishable key.`);
}
const buildConfig = supabaseUrl && supabaseKey ? { supabaseUrl: new URL(supabaseUrl).origin, supabaseKey } : {};
// Output folder (default build/). Override when build/ cannot be overwritten,
// e.g. CONTINUUM_EXTENSION_OUT_DIR=apps/browser-extension/build-local
const outDir = process.env.CONTINUUM_EXTENSION_OUT_DIR
  ? pathToFileURL(resolve(process.env.CONTINUUM_EXTENSION_OUT_DIR) + "/")
  : new URL("build/", root);

// Optional: custom local API origin for legacy fallback
const backendOrigin = process.env.CONTINUUM_EXTENSION_API_ORIGIN || "http://127.0.0.1:3101";
const backend = new URL(backendOrigin);

if (
  backend.protocol !== "https:" &&
  !["127.0.0.1", "localhost"].includes(backend.hostname)
)
  throw new Error("Custom extension backend must use HTTPS");

for (const browser of ["chrome", "firefox"]) {
  const target = new URL(`${browser}/`, outDir);
  await mkdir(target, { recursive: true });
  await cp(new URL("src/", root), target, { recursive: true });
  await writeFile(
    new URL("lib/build-config.js", target),
    `// Generated by build.mjs. Public values only.\nexport default ${JSON.stringify(buildConfig, null, 2)};\n`,
  );

  const manifest = {
    manifest_version: 3,
    name: "Continuum authorized capture",
    version: "0.2.1",
    description: "Capture ChatGPT and Claude conversations to Continuum memory.",
    permissions: ["storage", "alarms", "tabs", "activeTab", "scripting"],
    host_permissions: [
      "https://chatgpt.com/*",
      "https://claude.ai/*",
      "https://*.supabase.co/*",
    ],
    optional_host_permissions: [
      // Local fallback
      "http://127.0.0.1/*",
      "http://localhost/*",
      // Custom backend if provided
      ...new Set(
        backend.protocol === "https:" ? [backend.origin + "/*"] : []
      ),
    ],
    content_scripts: [
      {
        matches: ["https://chatgpt.com/*", "https://claude.ai/*"],
        js: ["content/capture.js"],
        run_at: "document_idle",
      },
    ],
    background:
      browser === "chrome"
        ? { service_worker: "background.js", type: "module" }
        : { scripts: ["background.js"], type: "module" },
    action: {
      default_popup: "popup.html",
      default_title: "Continuum capture",
    },
    options_ui: { page: "options.html", open_in_tab: true },
  };

  if (browser === "firefox") {
    manifest.browser_specific_settings = {
      gecko: {
        id: "continuum-capture@local.invalid",
        strict_min_version: "128.0",
        data_collection_permissions: {
          required: ["websiteContent"],
          optional: [],
        },
      },
    };
  }

  await writeFile(
    new URL("manifest.json", target),
    JSON.stringify(manifest, null, 2),
  );
}

console.log(`Extension built for chrome and firefox in ${outDir.pathname}`);
console.log(buildConfig.supabaseUrl
  ? `Default endpoint: ${buildConfig.supabaseUrl} (direct; no local server needed)`
  : "Default endpoint: local API http://127.0.0.1:3101 (no Supabase URL/key found in .env)");
